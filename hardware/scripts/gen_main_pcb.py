    cb = next(iter(contact_b.Pads())).GetPosition()
    add_track(board, out_b, pcbnew.B_Cu, POWER_TRACK, vb, (vb[0], edge_y), (cb.x - mm(0.8), edge_y),
              (cb.x, edge_y + mm(0.8)), (cb.x, cb.y))


